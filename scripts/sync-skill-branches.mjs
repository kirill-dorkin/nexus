// Copies branch membership (branch id → skill keys) from the Web skill map into the API,
// which draws branch tests from it (ADR-0075) until the map lives in Learning Content (P1.3).
// Run after rebuilding apps/web/src/lib/skill-map/skill-map.json:
//   node scripts/sync-skill-branches.mjs
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const map = JSON.parse(
  readFileSync(new URL("apps/web/src/lib/skill-map/skill-map.json", root), "utf8")
);
const branches = Object.fromEntries(
  map.characters.flatMap((character) =>
    character.branches.map((branch) => [
      branch.id,
      branch.skills.map((skill) => skill.key)
    ])
  )
);
const target = new URL(
  "apps/api/src/modules/learner-learning/domain/skill-branches.generated.ts",
  root
);
writeFileSync(
  target,
  `// Generated by scripts/sync-skill-branches.mjs from apps/web/src/lib/skill-map/skill-map.json.\n` +
    `// Do not edit: rerun the script after the skill map changes.\n\n` +
    `/** Branch id → its skill keys, in map order. */\n` +
    `export const SKILL_BRANCHES: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(branches)};\n`
);
spawnSync("pnpm", ["exec", "prettier", "--write", target.pathname], {
  stdio: "inherit"
});
