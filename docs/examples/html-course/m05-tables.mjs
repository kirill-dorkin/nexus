export default function tables(c) {
  const { html, mdn, lesson, single, multi, short } = c;

  lesson({
    slug: "tablicy", title: "Таблицы", minutes: 11,
    summary: "table, tr, th, td и caption: данные в строках и столбцах.",
    skill: ["html-tables", "Таблицы", "Размечать табличные данные со строкой заголовков и подписью."],
    body: [
      `## Таблица для данных`,
      html(`<table>
  <caption>Расписание занятий</caption>
  <tr>
    <th>День</th>
    <th>Тема</th>
    <th>Время</th>
  </tr>
  <tr>
    <td>Понедельник</td>
    <td>HTML</td>
    <td>19:00</td>
  </tr>
  <tr>
    <td>Среда</td>
    <td>CSS</td>
    <td>19:00</td>
  </tr>
</table>`),
      `- \`<table>\` — таблица.
- \`<tr>\` (table row) — строка.
- \`<th>\` (table header) — ячейка-заголовок. Браузер выделит её жирным и по центру, а читалка будет называть заголовок при чтении каждой ячейки столбца.
- \`<td>\` (table data) — обычная ячейка.
- \`<caption>\` — название таблицы. Первым элементом внутри \`table\`.`,
      `## Таблица строится по строкам`,
      `В HTML нет «столбцов» как элементов: вы описываете строки, а столбцы получаются из ячеек на одинаковых позициях. В каждой строке должно быть одинаковое число ячеек (с учётом объединений — о них в следующем уроке).`,
      `## Таблица — не для раскладки`,
      `Когда-то страницы раскладывали таблицами: меню в одной ячейке, контент в другой. Сейчас так не делают: читалка объявит «таблица, 2 столбца», и человек будет искать там данные. Для раскладки есть CSS (Flexbox и Grid). Таблица — только для данных, у которых есть строки и столбцы.`,
      `## Широкие таблицы на телефоне`,
      `Таблица из 6 столбцов не поместится на узком экране. Частое решение — обернуть её в блок с горизонтальной прокруткой (это делают CSS). Подумайте и о том, нельзя ли показать меньше столбцов.`,
      `## Практика`,
      `Сделайте в песочнице таблицу трёх любимых фильмов: название, год, оценка. Не забудьте \`caption\` и строку заголовков \`th\`.`,
      mdn("Element/table", "Элемент table")
    ],
    quizzes: [
      single("tables-th", "Ячейка-заголовок", "Каким тегом размечают ячейку-заголовок столбца?",
        [["th", "<th>"], ["td", "<td>"], ["tr", "<tr>"], ["caption", "<caption>"]], "th",
        "th — ячейка-заголовок. td — обычная ячейка, tr — строка, caption — название таблицы."),
      single("tables-layout", "Когда нужна таблица", "В каком случае таблица — правильный выбор?",
        [["data", "Сравнение тарифов по цене и возможностям"], ["layout", "Колонка меню слева и контент справа"], ["center", "Чтобы отцентрировать картинку"], ["footer", "Подвал сайта в три колонки"]], "data",
        "Таблица — для табличных данных. Раскладку страницы делают CSS."),
      short("tables-caption", "Название таблицы", "Каким элементом задают название таблицы? Введите имя тега без скобок.",
        ["caption"], "Название таблицы — элемент caption, первым внутри table.")
    ]
  });

  lesson({
    slug: "slozhnye-tablicy", title: "Сложные таблицы", minutes: 12,
    summary: "thead, tbody, tfoot, scope, colspan, rowspan, headers и colgroup: таблицы, понятные и людям, и читалкам.",
    skill: ["html-tables-advanced", "Сложные таблицы", "Группировать строки, объединять ячейки и явно связывать ячейки с заголовками строк и столбцов."],
    body: [
      `## Шапка, тело, итог`,
      html(`<table>
  <caption>Расходы за неделю</caption>
  <thead>
    <tr><th scope="col">День</th><th scope="col">Сумма, ₽</th></tr>
  </thead>
  <tbody>
    <tr><th scope="row">Понедельник</th><td>450</td></tr>
    <tr><th scope="row">Вторник</th><td>1200</td></tr>
  </tbody>
  <tfoot>
    <tr><th scope="row">Итого</th><td>1650</td></tr>
  </tfoot>
</table>`),
      `- \`<thead>\` — строки заголовков, \`<tbody>\` — данные, \`<tfoot>\` — итоги. При печати длинной таблицы браузер повторит шапку на каждой странице.
- Заголовки бывают и у строк: первая ячейка строки «Понедельник» — тоже \`th\`.`,
      `## scope — чей это заголовок`,
      `\`scope="col"\` — заголовок столбца, \`scope="row"\` — заголовок строки. В простых таблицах браузер догадается сам, но явный \`scope\` делает чтение надёжным: читалка произнесёт «Вторник, Сумма, 1200».`,
      `## Объединение ячеек`,
      html(`<table>
  <caption>Расписание</caption>
  <tr>
    <th scope="col">Время</th>
    <th scope="col">Пн</th>
    <th scope="col">Вт</th>
  </tr>
  <tr>
    <th scope="row">10:00</th>
    <td rowspan="2">HTML (2 часа)</td>
    <td>CSS</td>
  </tr>
  <tr>
    <th scope="row">11:00</th>
    <td>JavaScript</td>
  </tr>
  <tr>
    <td colspan="3">Обед</td>
  </tr>
</table>`),
      `- \`colspan="3"\` — ячейка шириной в три столбца.
- \`rowspan="2"\` — ячейка высотой в две строки. В следующей строке для этого места ячейку **не пишут**.

Объединения усложняют чтение для читалок — используйте их, когда без них данные действительно непонятны.`,
      `## headers — для очень сложных таблиц`,
      html(`<table>
  <tr><th id="q1" scope="col">I квартал</th><th id="q2" scope="col">II квартал</th></tr>
  <tr><td headers="q1">120</td><td headers="q2">180</td></tr>
</table>`),
      `Когда у ячейки несколько уровней заголовков, атрибут \`headers\` явно перечисляет \`id\` нужных \`th\` через пробел.`,
      `## Группы столбцов: colgroup`,
      html(`<table>
  <colgroup>
    <col>
    <col span="2" style="background: #f3f9d2">
  </colgroup>
  <tr><th>Товар</th><th>Цена</th><th>Скидка</th></tr>
  <tr><td>Футболка</td><td>990</td><td>10%</td></tr>
</table>`),
      `\`colgroup\` и \`col\` позволяют обратиться к целому столбцу, например подсветить его. Стилизовать через них можно лишь несколько свойств (фон, ширину, рамки).`,
      `## Практика`,
      `Сделайте в песочнице таблицу оценок за четверть: столбцы — предметы, строки — ученики, в \`tfoot\` — средний балл. Расставьте \`scope\`.`,
      mdn("Element/th", "Элемент th")
    ],
    quizzes: [
      single("tables-scope", "Заголовок строки", "Как отметить, что ячейка <th> — заголовок строки, а не столбца?",
        [["row", "scope=\"row\""], ["col", "scope=\"col\""], ["rowspan", "rowspan=\"1\""], ["headers", "headers=\"row\""]], "row",
        "scope=\"row\" связывает заголовок со всей строкой, scope=\"col\" — со столбцом."),
      single("tables-colspan", "Широкая ячейка", "Как сделать ячейку шириной в три столбца?",
        [["colspan", "colspan=\"3\""], ["rowspan", "rowspan=\"3\""], ["width", "width=\"3\""], ["span", "span=\"3\" у td"]], "colspan",
        "colspan объединяет ячейки по горизонтали, rowspan — по вертикали."),
      multi("tables-groups", "Группы строк", "Какие элементы группируют строки таблицы?",
        [["thead", "<thead>"], ["tbody", "<tbody>"], ["tfoot", "<tfoot>"], ["colgroup", "<colgroup>"]], ["thead", "tbody", "tfoot"],
        "thead, tbody и tfoot группируют строки. colgroup группирует столбцы.")
    ]
  });
}
