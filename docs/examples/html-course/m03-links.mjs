export default function links(c) {
  const { html, code, mdn, lesson, single, short } = c;

  lesson({
    slug: "ssylki", title: "Ссылки", minutes: 11,
    summary: "Тег a и атрибут href: ссылки на сайты, страницы, почту, телефон и места на странице.",
    skill: ["html-links", "Ссылки", "Ставить ссылки на другие сайты, страницы, почту, телефон и якоря с понятным текстом."],
    body: [
      `## Ссылка = текст + адрес`,
      html(`<p>Справочник по HTML — <a href="https://developer.mozilla.org/ru/">MDN</a>.</p>`),
      `Текст между тегами — то, на что нажимают. \`href\` (hypertext reference) — куда ведёт. Ссылки — то, что превращает отдельные страницы в веб.`,
      `## Почта и телефон`,
      html(`<a href="mailto:hello@example.com">Написать нам</a><br>
<a href="mailto:hello@example.com?subject=Вопрос%20по%20курсу">Письмо с темой</a><br>
<a href="tel:+79990000000">+7 999 000-00-00</a>`),
      `\`mailto:\` открывает почтовую программу, \`tel:\` — звонилку на телефоне. Номер в \`tel:\` пишите в международном формате без пробелов.`,
      `## Якоря — ссылки внутри страницы`,
      html(`<nav>
  <a href="#about">О курсе</a> ·
  <a href="#price">Цена</a>
</nav>

<h2 id="about">О курсе</h2>
<p>Подробное описание…</p>

<h2 id="price">Цена</h2>
<p>Бесплатно.</p>`),
      `\`#price\` ведёт к элементу с \`id="price"\`. Можно сослаться и на место другой страницы: \`/faq#delivery\`. Ссылка \`href="#"\` прокручивает в начало страницы.`,
      `## Новая вкладка`,
      html(`<a href="https://example.com" target="_blank" rel="noopener">Открыть в новой вкладке</a>`),
      `\`target="_blank"\` открывает новую вкладку. Не злоупотребляйте: человек сам решит, где открыть. Используйте для внешних материалов, когда уход со страницы потеряет данные (например, во время заполнения формы).`,
      `## Текст ссылки объясняет, куда она ведёт`,
      `Плохо: «нажмите **здесь**», «подробнее», голый адрес. Хорошо: «скачайте **программу курса (PDF, 2 МБ)**». Человек с экранной читалкой часто слушает только список ссылок на странице — «здесь, здесь, здесь» ему ничего не скажет.`,
      `## Ссылка или кнопка?`,
      `Ссылка **ведёт куда-то** — на другую страницу или место. Кнопка **делает что-то** — отправляет форму, открывает окно. Не делайте «ссылку», которая ничего не открывает, и «кнопку», которая просто переходит на страницу.`,
      `## Практика`,
      `Сделайте в песочнице мини-меню: ссылка на MDN, на почту с темой письма и якорем на раздел «Контакты» ниже.`,
      mdn("Element/a", "Элемент a")
    ],
    quizzes: [
      short("links-href", "Атрибут адреса", "Какой атрибут тега <a> хранит адрес ссылки?",
        ["href"], "Адрес ссылки хранится в атрибуте href."),
      single("links-anchor", "Якорь", "Куда ведёт ссылка <a href=\"#faq\">Вопросы</a>?",
        [["id", "К элементу с id=\"faq\" на этой же странице"], ["site", "На сайт faq.com"], ["file", "К файлу faq.html"], ["none", "Никуда, это ошибка"]], "id",
        "Решётка в начале href означает якорь: переход к элементу с таким id на текущей странице."),
      single("links-text", "Понятный текст", "Какой текст ссылки лучше всего?",
        [["good", "Скачать программу курса (PDF)"], ["here", "Здесь"], ["click", "Нажмите сюда"], ["url", "https://example.com/files/program-final-v2.pdf"]], "good",
        "Текст ссылки должен сам объяснять, что будет после нажатия."),
      single("links-vs-button", "Ссылка или кнопка", "Элемент отправляет форму заказа. Что это должно быть?",
        [["button", "Кнопка <button>"], ["a", "Ссылка <a href=\"#\">"], ["span", "<span> с обработчиком"], ["div", "<div>"]], "button",
        "Действие — это кнопка. Ссылка ведёт на другой адрес.")
    ]
  });

  lesson({
    slug: "puti-k-fajlam", title: "Пути к файлам и структура сайта", minutes: 11,
    summary: "Абсолютные и относительные адреса, ./ и ../, корень сайта и index.html.",
    skill: ["html-paths", "Пути к файлам", "Составлять абсолютные, относительные и корневые адреса к страницам и файлам сайта."],
    body: [
      `## Сайт — это папка с файлами`,
      `Представим такой сайт:`,
      code("text", `site/
├── index.html
├── about.html
├── images/
│   └── logo.png
└── blog/
    ├── index.html
    └── first-post.html`),
      `## Три вида адресов`,
      `1. **Абсолютный** — полный, с протоколом и доменом: \`https://example.com/blog/first-post.html\`. Нужен для ссылок на чужие сайты.
2. **Корневой** — от корня текущего сайта, начинается с \`/\`: \`/images/logo.png\`. Работает одинаково с любой страницы сайта.
3. **Относительный** — от текущего файла: \`about.html\`, \`images/logo.png\`, \`../index.html\`.`,
      `## Как читать относительный путь`,
      `Допустим, мы в файле \`blog/first-post.html\`:
- \`index.html\` → \`blog/index.html\` (та же папка);
- \`./index.html\` → то же самое, \`./\` значит «текущая папка»;
- \`../about.html\` → \`about.html\` в корне: \`../\` поднимает на уровень выше;
- \`../images/logo.png\` → картинка в корневой папке images.`,
      html(`<!-- Внутри blog/first-post.html -->
<a href="../index.html">На главную</a>
<a href="index.html">Все записи блога</a>
<img src="../images/logo.png" alt="Логотип">`),
      `## index.html и красивые адреса`,
      `Если адрес заканчивается на папку (\`/blog/\`), сервер отдаст \`index.html\` из неё. Поэтому ссылку на блог можно писать \`/blog/\` вместо \`/blog/index.html\`.`,
      `## Правила имён файлов`,
      `- Только латиница, цифры и дефисы: \`first-post.html\`, а не \`Первый пост.html\`.
- Строчные буквы: на серверах \`Logo.png\` и \`logo.png\` — **разные** файлы.
- Без пробелов: пробел в адресе превращается в \`%20\`.`,
      `## Какой путь выбрать`,
      `Для своего сайта удобны корневые пути (\`/images/logo.png\`): их не нужно пересчитывать при переносе страницы в другую папку. Относительные хороши, когда сайт открывают прямо с диска без сервера — там корневые пути указывают на корень диска.`,
      `## Практика`,
      `Для структуры выше ответьте себе: как из \`about.html\` сослаться на \`blog/first-post.html\`, а из \`blog/first-post.html\` — на \`about.html\`? Проверьте себя в заданиях ниже.`,
      mdn("../../Learn/HTML/Introduction_to_HTML/Creating_hyperlinks", "Создание ссылок")
    ],
    quizzes: [
      single("paths-up", "Уровень выше", "Вы в файле blog/first-post.html. Какой путь ведёт к about.html в корне сайта?",
        [["up", "../about.html"], ["same", "about.html"], ["dot", "./about.html"], ["blog", "blog/about.html"]], "up",
        "../ поднимает на одну папку вверх — из blog в корень, где лежит about.html."),
      single("paths-root", "Корневой путь", "Что означает адрес, начинающийся с / (например /images/logo.png)?",
        [["root", "Путь от корня текущего сайта"], ["here", "Путь от текущей папки"], ["disk", "Путь от корня жёсткого диска на сервере"], ["web", "Путь на другой сайт"]], "root",
        "Ведущий слеш означает корень сайта, поэтому такой путь одинаково работает с любой страницы."),
      single("paths-names", "Имя файла", "Какое имя файла лучше всего подходит для веба?",
        [["good", "first-post.html"], ["space", "first post.html"], ["cyr", "первый-пост.html"], ["upper", "First_Post.HTML"]], "good",
        "Латиница в нижнем регистре, цифры и дефисы — надёжнее всего: без кодирования и путаницы с регистром.")
    ]
  });

  lesson({
    slug: "vozmozhnosti-ssylok", title: "Возможности ссылок", minutes: 9,
    summary: "download, rel, hreflang и type: скачивание файлов и подсказки браузеру и поисковикам.",
    skill: ["html-link-attributes", "Атрибуты ссылок", "Использовать download, rel, hreflang и type по назначению."],
    body: [
      `## Скачать вместо открыть`,
      html(`<a href="/files/program.pdf" download>Скачать программу (PDF, 2 МБ)</a>
<a href="/files/report-2026.pdf" download="Отчёт-Nexus.pdf">Скачать отчёт</a>`),
      `Атрибут \`download\` просит браузер сохранить файл, а не открыть его. Значение задаёт имя сохраняемого файла. Работает для файлов с того же сайта. Указывайте в тексте тип и размер файла — человек должен знать, что скачивает.`,
      `## rel — связь со ссылкой`,
      `\`rel\` (relationship) объясняет, как текущая страница связана с целью:`,
      `- \`noopener\` — новая вкладка не получит доступ к вашей странице через JavaScript. Современные браузеры добавляют это поведение к \`target="_blank"\` автоматически, но явно — надёжнее.
- \`noreferrer\` — не передавать сайту-цели, откуда пришёл человек.
- \`nofollow\` — «я не ручаюсь за эту ссылку»: поисковики не передают ей вес. Для ссылок в комментариях пользователей.
- \`sponsored\` — рекламная ссылка, \`ugc\` — ссылка из пользовательского контента.
- \`external\` — ссылка ведёт на другой сайт.`,
      html(`<a href="https://partner.example" rel="sponsored noopener" target="_blank">Партнёр курса</a>`),
      `Значений можно указать несколько через пробел.`,
      `## hreflang и type`,
      html(`<a href="/en/" hreflang="en" lang="en">English version</a>
<a href="/files/data.csv" type="text/csv" download>Данные в CSV</a>`),
      `\`hreflang\` сообщает язык страницы по ссылке, \`type\` — тип файла. Браузер их не проверяет, это подсказки для поисковиков и программ.`,
      `## Ссылка-картинка`,
      html(`<a href="/">
  <img src="https://picsum.photos/seed/logo/80/80" alt="Nexus — на главную" width="80" height="80">
</a>`),
      `Если ссылка состоит только из картинки, \`alt\` должен описывать **куда ведёт ссылка**, а не что нарисовано.`,
      `## Практика`,
      `Сделайте в песочнице блок «Материалы»: ссылку на скачивание конспекта с указанием формата и размера и внешнюю ссылку на MDN в новой вкладке с правильным \`rel\`.`,
      mdn("Attributes/rel", "Атрибут rel")
    ],
    quizzes: [
      short("link-download", "Скачивание", "Какой атрибут ссылки просит браузер сохранить файл, а не открыть его?",
        ["download"], "Атрибут download предлагает скачать файл; его значение задаёт имя файла."),
      single("link-nofollow", "Чужие ссылки", "Какой rel подходит для ссылок, которые пользователи оставили в комментариях?",
        [["ugc", "ugc (или nofollow)"], ["noopener", "noopener"], ["external", "external"], ["download", "download"]], "ugc",
        "ugc и nofollow сообщают поисковикам, что сайт не ручается за ссылку."),
      single("link-image-alt", "Ссылка-картинка", "Ссылка на главную состоит только из логотипа. Каким должен быть alt?",
        [["dest", "Куда ведёт ссылка: «Nexus — на главную»"], ["draw", "Описание рисунка: «зелёный квадрат с точками»"], ["empty", "Пустым"], ["file", "Имя файла logo.png"]], "dest",
        "Для единственной картинки в ссылке alt становится текстом ссылки, поэтому описывает назначение.")
    ]
  });
}
