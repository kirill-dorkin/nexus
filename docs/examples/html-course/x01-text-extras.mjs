export function divSpan(c) {
  const { html, mdn, lesson, single, multi } = c;
  lesson({
    slug: "blochnye-i-strochnye", title: "Блочные и строчные элементы: div и span", minutes: 10,
    summary: "Почему одни элементы встают с новой строки, а другие — нет, и зачем нужны «пустые» div и span.",
    skill: ["html-block-inline", "Блочные и строчные элементы", "Различать блочные и строчные элементы и использовать div и span как контейнеры без смысла."],
    body: [
      `## Два поведения по умолчанию`,
      html(`<p>Абзац занимает всю ширину.</p>
<p>Следующий абзац — с новой строки.</p>
<p>А <strong>strong</strong>, <a href="#">ссылка</a> и <em>em</em> стоят внутри строки.</p>`),
      `- **Блочные** элементы (\`p\`, \`h1\`–\`h6\`, \`ul\`, \`li\`, \`div\`, \`section\`, \`table\`, \`form\`) начинаются с новой строки и растягиваются на всю ширину.
- **Строчные** (\`a\`, \`strong\`, \`em\`, \`span\`, \`img\`, \`code\`, \`input\`) встают в поток текста, как слова.

Это поведение задаёт CSS-свойство \`display\`, и его можно поменять: например, сделать ссылки меню блочными. Но **смысл** элемента от этого не меняется.`,
      `## div — блочный контейнер без смысла`,
      html(`<div class="card">
  <h3>Курс HTML</h3>
  <p>50 уроков с практикой.</p>
</div>
<div class="card">
  <h3>Курс CSS</h3>
  <p>Скоро.</p>
</div>`),
      `\`div\` группирует элементы, чтобы их оформить или разместить: карточка, колонка, обёртка. Он ничего не сообщает читалкам и поисковикам.`,
      `## span — строчный контейнер без смысла`,
      html(`<p>Осталось <span class="count">3</span> места.</p>`),
      `\`span\` выделяет часть текста для оформления или скрипта.`,
      `## Сначала смысл, потом div`,
      `Прежде чем написать \`div\`, спросите: нет ли подходящего элемента? Шапка — \`header\`, навигация — \`nav\`, статья — \`article\`, список карточек — \`ul\` с \`li\`, важный текст — \`strong\`. \`div\` и \`span\` — для случаев, когда смысла действительно нет. Страница из одних \`div\` («div-суп») работает, но недоступна и плохо читается.`,
      `## Практика`,
      `Сверстайте в песочнице три карточки тарифов: оберните каждую в \`div class="plan"\`, внутри — заголовок, цена (\`span class="price"\`) и список возможностей. Подумайте: не подойдёт ли вместо \`div\` элемент \`article\` или \`li\`?`,
      mdn("Element/div", "Элемент div")
    ],
    quizzes: [
      multi("block-which", "Блочные элементы", "Какие элементы по умолчанию блочные?",
        [["p", "<p>"], ["div", "<div>"], ["ul", "<ul>"], ["a", "<a>"], ["span", "<span>"]], ["p", "div", "ul"],
        "p, div и ul начинаются с новой строки. a и span — строчные."),
      single("block-div", "Когда div", "В каком случае div — правильный выбор?",
        [["layout", "Обёртка двух колонок только ради раскладки"], ["nav", "Главное меню сайта"], ["article", "Отдельная статья блога"], ["important", "Важное предупреждение в тексте"]], "layout",
        "div — для группировки без смысла. Для меню есть nav, для статьи — article, для важного — strong.")
    ]
  });
}

export function bidiRuby(c) {
  const { html, mdn, lesson, single } = c;
  lesson({
    slug: "yazyki-i-napravlenie", title: "Языки, направление текста и ruby", minutes: 9,
    summary: "lang, dir, bdi, bdo и ruby: текст на разных языках, справа налево и подписи произношения.",
    skill: ["html-i18n-text", "Многоязычный текст", "Размечать фрагменты на других языках, текст справа налево и подписи произношения ruby."],
    body: [
      `## Язык фрагмента`,
      html(`<p>Слово <span lang="en">deadline</span> прочно вошло в офисный язык.</p>
<blockquote lang="de"><p>Übung macht den Meister.</p></blockquote>`),
      `\`lang\` у фрагмента помогает читалке переключить произношение, браузеру — правильно расставить переносы и кавычки, переводчику — понять, что переводить.`,
      `## Справа налево: dir`,
      html(`<p dir="rtl" lang="he">שלום עולם</p>
<p dir="auto">مرحبا — направление определится автоматически</p>`),
      `Иврит, арабский и персидский пишутся справа налево. \`dir="rtl"\` переворачивает направление блока, \`dir="auto"\` угадывает по первым символам — удобно для текста, который вводят пользователи.`,
      `## bdi — изолировать неизвестный текст`,
      html(`<ul>
  <li>Пользователь <bdi>إيان</bdi>: 3 комментария</li>
  <li>Пользователь <bdi>Анна</bdi>: 5 комментариев</li>
</ul>`),
      `Если в строку попадает имя на арабском, соседние цифры и знаки могут «перескочить» не на своё место. \`bdi\` изолирует фрагмент, чтобы он не ломал направление окружающего текста. \`bdo dir="rtl"\` — наоборот, принудительно переворачивает текст.`,
      `## ruby — подписи произношения`,
      html(`<p>
  <ruby>漢<rp>(</rp><rt>kan</rt><rp>)</rp>字<rp>(</rp><rt>ji</rt><rp>)</rp></ruby> — японские иероглифы.
</p>
<p><ruby>Москва<rt>Moskva</rt></ruby></p>`),
      `\`ruby\` выводит маленькую подпись над текстом — так в японском и китайском показывают чтение иероглифов. \`rt\` — подпись, \`rp\` — скобки для браузеров без поддержки ruby. Можно использовать и для транслитерации или ударений в учебных текстах.`,
      `## Практика`,
      `Сделайте в песочнице мини-словарь: русское слово, рядом английское в \`span lang="en"\` и японское с подписью чтения через \`ruby\`.`,
      mdn("Element/ruby", "Элемент ruby")
    ],
    quizzes: [
      single("i18n-dir", "Направление", "Какой атрибут переключает направление текста справа налево?",
        [["dir", "dir=\"rtl\""], ["lang", "lang=\"rtl\""], ["align", "align=\"right\""], ["rtl", "rtl=\"true\""]], "dir",
        "Направление задаётся атрибутом dir: rtl, ltr или auto."),
      single("i18n-ruby", "Подпись чтения", "Каким элементом внутри ruby задают подпись произношения?",
        [["rt", "<rt>"], ["rp", "<rp>"], ["sup", "<sup>"], ["small", "<small>"]], "rt",
        "rt — текст подписи, rp — запасные скобки.")
    ]
  });
}

export function projectRecipe(c) {
  const { html, lesson, multi } = c;
  lesson({
    slug: "mini-proekt-recept", title: "Мини-проект: страница рецепта", minutes: 20,
    summary: "Соберите полноценную текстовую страницу: заголовки, списки, выделения, время, термины и характеристики.",
    skill: ["html-project-recipe", "Мини-проект: рецепт", "Сверстать текстовую страницу, используя заголовки, списки, строчную семантику и списки определений."],
    body: [
      `## Задача`,
      `Сверстайте страницу любимого рецепта. Проект закрепляет модули «Основы» и «Текст» — без картинок и стилей, только смысловая разметка.`,
      `## Требования`,
      `1. Каркас документа с \`lang\`, кодировкой и \`title\`.
2. \`h1\` — название блюда, абзац-описание с одним \`strong\` (что важно) и одним \`em\`.
3. Характеристики в \`dl\`: время готовки в \`time\` с \`datetime\` (например \`PT45M\`), сложность, порции.
4. «Ингредиенты» — \`h2\` и маркированный список с количеством; граммы через неразрывный пробел (\`200&nbsp;г\`).
5. «Приготовление» — \`h2\` и нумерованный список шагов; на одном шаге — сочетание клавиш таймера в \`kbd\` (шутки ради) или температура \`180&nbsp;°C\`.
6. «Совет шефа» — цитата \`blockquote\` с источником в \`figure\` и \`figcaption\`.
7. Внизу — \`small\` с примечанием и \`abbr\` для «ст. л.».`,
      `## Заготовка`,
      html(`<!doctype html>
<html lang="ru">
<head>
  <meta charset="utf-8">
  <title>Сырники — рецепт</title>
</head>
<body>
  <h1>Сырники</h1>
  <p><!-- Описание со strong и em --></p>

  <dl>
    <dt>Время</dt>
    <dd><time datetime="PT30M">30 минут</time></dd>
    <!-- Сложность и порции -->
  </dl>

  <h2>Ингредиенты</h2>
  <ul>
    <li>Творог — 400&nbsp;г</li>
  </ul>

  <h2>Приготовление</h2>
  <ol>
    <li>Смешайте творог с яйцом.</li>
  </ol>
</body>
</html>`),
      `## Чек-лист`,
      `- Один \`h1\`, разделы на \`h2\`.
- Ингредиенты — \`ul\`, шаги — \`ol\`.
- Каждый тег выделения выбран по смыслу.
- Число и единица измерения не разрываются.
- Код без ошибок в валидаторе.`
    ],
    quizzes: [
      multi("recipe-check", "Проверка рецепта", "Какие решения правильные для страницы рецепта?",
        [["ol", "Шаги приготовления — нумерованный список ol"], ["dl", "Время и порции — список определений dl"], ["nbsp", "Неразрывный пробел между числом и «г»"], ["br", "Ингредиенты через <br> в одном абзаце"], ["h3", "Название блюда в h3, чтобы было поменьше"]], ["ol", "dl", "nbsp"],
        "Порядок шагов важен — ol; пары название-значение — dl; число и единица не разрываются. Список через br и неверный уровень заголовка — ошибки.")
    ]
  });
}
