export default function a11y(c) {
  const { html, code, mdn, lesson, single, multi, short } = c;

  lesson({
    slug: "dostupnost-osnovy", title: "Доступность: основы", minutes: 12,
    summary: "Кто пользуется сайтом иначе, чем вы, и как правильный HTML решает большинство проблем бесплатно.",
    skill: ["html-a11y-basics", "Основы доступности", "Проверять страницу на базовую доступность: семантика, альтернативный текст, заголовки, подписи, язык."],
    body: [
      `## Для кого это`,
      `Доступность (accessibility, a11y) — возможность пользоваться сайтом для всех: незрячих людей с экранными читалками, слабовидящих с увеличением, людей, которые не могут пользоваться мышью, глухих, людей с когнитивными особенностями, а ещё — для человека с телефоном на солнце или со сломанной рукой. Это около миллиарда людей.`,
      `## Хорошая новость`,
      `Правильный HTML доступен сам по себе. Кнопка \`<button>\` уже фокусируется, нажимается с клавиатуры и называется читалкой «кнопка». \`<div onclick>\` не умеет ничего из этого. Большинство проблем доступности — это неправильно выбранные элементы.`,
      `## Чек-лист базовой доступности`,
      `1. **Язык страницы** — \`<html lang="ru">\`.
2. **Заголовки** — один \`h1\`, иерархия без пропусков.
3. **Ориентиры** — \`header\`, \`nav\`, \`main\`, \`footer\`.
4. **Картинки** — осмысленный \`alt\`, у декоративных пустой.
5. **Ссылки и кнопки** — понятный текст; ссылка ведёт, кнопка действует.
6. **Формы** — у каждого поля \`label\`, у групп — \`fieldset\` и \`legend\`, ошибки описаны текстом.
7. **Таблицы** — \`th\` и \`caption\`.
8. **Медиа** — субтитры к видео, расшифровка к аудио.
9. **Клавиатура** — всё работает без мыши (следующий урок).
10. **Цвет** — информация не передаётся только цветом («обязательные поля отмечены красным» — плохо; добавьте текст или звёздочку с пояснением).`,
      `## Плохо и хорошо`,
      html(`<!-- Плохо: не фокусируется, читалка не поймёт, что это кнопка -->
<div class="btn" onclick="buy()">Купить</div>

<!-- Хорошо -->
<button type="button">Купить</button>`),
      `## Как проверить`,
      `- Пройдите страницу только клавиатурой: Tab, Shift+Tab, Enter, пробел, стрелки.
- Включите читалку: VoiceOver на Mac и iPhone (⌘+F5), NVDA на Windows (бесплатно), TalkBack на Android.
- DevTools → вкладка Lighthouse → Accessibility; дерево доступности во вкладке Elements → Accessibility.
- Увеличьте страницу до 200% — ничего не должно обрезаться.`,
      `## Стандарт WCAG`,
      `Требования к доступности собраны в стандарте **WCAG** (Web Content Accessibility Guidelines). Уровень AA — то, к чему стремятся большинство сайтов и что требуют законы многих стран.`,
      `## Практика`,
      `Найдите в песочнице 5 проблем доступности в коде ниже и исправьте их.`,
      html(`<html>
<div class="header">Магазин</div>
<img src="https://picsum.photos/seed/shoe/200/120">
<h3>Кроссовки</h3>
<input placeholder="Ваш email">
<div onclick="buy()">Купить</div>
</html>`),
      mdn("../Accessibility", "Доступность")
    ],
    quizzes: [
      single("a11y-div-button", "div вместо кнопки", "Чем плох <div onclick=\"…\">Купить</div> по сравнению с <button>?",
        [["all", "Не получает фокус с клавиатуры, не нажимается Enter и не называется читалкой кнопкой"], ["style", "Только тем, что выглядит иначе"], ["slow", "Он медленнее работает"], ["nothing", "Ничем, это одно и то же"]], "all",
        "button даёт фокус, управление с клавиатуры и правильную роль бесплатно. div — ничего из этого."),
      multi("a11y-checklist", "Базовые проверки", "Что из этого входит в базовую доступность страницы?",
        [["lang", "Атрибут lang у html"], ["alt", "alt у картинок"], ["labels", "label у полей формы"], ["color", "Отмечать ошибки только красным цветом"], ["zoom", "Запрет масштабирования"]], ["lang", "alt", "labels"],
        "Язык, alt и подписи полей — основа. Информация только цветом и запрет масштабирования мешают людям."),
      short("a11y-wcag", "Стандарт", "Как называется международный стандарт требований к доступности веб-контента? Аббревиатура латиницей.",
        ["WCAG"], "WCAG — Web Content Accessibility Guidelines.")
    ]
  });

  lesson({
    slug: "klaviatura-i-fokus", title: "Клавиатура и фокус", minutes: 11,
    summary: "Порядок табуляции, tabindex, видимый фокус и ловушки: сайт, которым можно пользоваться без мыши.",
    skill: ["html-keyboard", "Клавиатура и фокус", "Обеспечивать логичный порядок фокуса, видимый индикатор и управление без мыши."],
    body: [
      `## Без мыши`,
      `Многие пользуются сайтом только с клавиатуры: из-за моторных нарушений, с читалкой или просто по привычке. **Tab** переходит к следующему интерактивному элементу, **Shift+Tab** — к предыдущему, **Enter** активирует ссылку и кнопку, **пробел** — кнопку и флажок, **стрелки** — переключатели и списки, **Escape** закрывает окна.`,
      `## Что получает фокус сам`,
      `Ссылки с \`href\`, кнопки, поля форм, \`select\`, \`textarea\`, \`summary\`. Всё остальное фокус не получает — и не должно, если оно не интерактивно.`,
      `## Порядок фокуса = порядок в HTML`,
      `Tab идёт в порядке элементов в коде. Если CSS переставил блоки визуально (например, через \`order\` во Flexbox), фокус будет прыгать по экрану хаотично. Держите порядок в HTML логичным.`,
      `## tabindex`,
      html(`<div tabindex="0">Можно сфокусировать Tab</div>
<h2 id="results" tabindex="-1">Результаты</h2>`),
      `- \`tabindex="0"\` — элемент встаёт в обычный порядок табуляции. Нужно редко: для собственных интерактивных компонентов (а им нужны ещё роль и обработка клавиш).
- \`tabindex="-1"\` — Tab его пропускает, но фокус можно поставить скриптом: например, перевести на заголовок результатов поиска.
- \`tabindex="1"\` и больше — **не используйте**: такой элемент перехватит фокус раньше всех и сломает порядок.`,
      `## Фокус должен быть виден`,
      `Браузер рисует рамку вокруг элемента в фокусе. Никогда не убирайте её стилями (\`outline: none\`) без замены — человек с клавиатурой потеряет, где он находится. Пройдитесь Tab по этому сайту и посмотрите, как подсвечивается фокус.`,
      `## Ловушки фокуса`,
      `Фокус не должен застревать: если Tab попал в виджет, из него должен быть выход. Исключение — модальный \`dialog\`: там фокус намеренно заперт, пока окно открыто, а Escape его закрывает. Браузер делает это сам.`,
      `## Пропуск повторяющихся блоков`,
      `Ссылка «Перейти к содержимому» в начале страницы экономит десятки нажатий Tab. Об этом — в уроке про семантическую структуру.`,
      `## Практика`,
      `В песочнице соберите форму из трёх полей и кнопки, затем пройдите её Tab в окне результата. Добавьте элементу \`tabindex="1"\` и посмотрите, как ломается порядок. Уберите.`,
      mdn("Global_attributes/tabindex", "Атрибут tabindex")
    ],
    quizzes: [
      single("keyboard-positive", "Положительный tabindex", "Почему не стоит использовать tabindex=\"3\"?",
        [["order", "Элемент перехватит фокус раньше остальных и сломает естественный порядок"], ["invalid", "Браузер не поддерживает значения больше 1"], ["hide", "Элемент станет невидимым"], ["nothing", "Это лучший способ задать порядок"]], "order",
        "Положительные значения выдёргивают элемент из естественного порядка. Порядок задают расположением в HTML."),
      single("keyboard-outline", "Рамка фокуса", "Дизайнеру не нравится рамка вокруг кнопок при нажатии Tab. Что делать?",
        [["restyle", "Перерисовать индикатор фокуса в стиле сайта, но оставить его видимым"], ["remove", "Убрать через outline: none"], ["tabindex", "Поставить всем tabindex=\"-1\""], ["ignore", "Убрать кнопки"]], "restyle",
        "Индикатор фокуса обязателен для пользователей клавиатуры. Его можно перекрасить, но не убрать."),
      single("keyboard-minus-one", "tabindex=\"-1\"", "Что делает tabindex=\"-1\"?",
        [["script", "Tab пропускает элемент, но фокус можно поставить скриптом"], ["disable", "Отключает элемент"], ["first", "Делает элемент первым в порядке"], ["hide", "Скрывает элемент"]], "script",
        "-1 убирает элемент из табуляции, но позволяет фокусировать его программно.")
    ]
  });

  lesson({
    slug: "aria", title: "ARIA: когда нужна и когда нет", minutes: 12,
    summary: "role, aria-label, aria-labelledby, aria-describedby, aria-expanded, aria-live и главное правило ARIA.",
    skill: ["html-aria", "ARIA", "Применять ARIA-атрибуты там, где HTML не хватает, и не применять там, где хватает."],
    body: [
      `## Что такое ARIA`,
      `ARIA (Accessible Rich Internet Applications) — атрибуты, которые сообщают читалкам роль, имя и состояние элемента. Они **ничего не меняют** во внешнем виде и поведении — только в том, как элемент объявляется.`,
      `## Первое правило ARIA`,
      `**Если можно использовать нативный HTML-элемент — используйте его.** \`<button>\` лучше, чем \`<div role="button" tabindex="0">\` с обработкой Enter и пробела вручную. Неправильная ARIA хуже, чем никакой: она обманывает читалку.`,
      `## Имя: aria-label и aria-labelledby`,
      html(`<!-- Кнопка-иконка без текста -->
<button type="button" aria-label="Закрыть">×</button>

<!-- Имя из видимого текста на странице -->
<h2 id="cart-title">Корзина</h2>
<section aria-labelledby="cart-title">…</section>`),
      `- \`aria-label\` — имя, когда видимого текста нет (кнопка-крестик, иконка-лупа).
- \`aria-labelledby\` — имя берётся из другого элемента по \`id\`. Предпочтительнее: видимый текст и имя не разойдутся.`,
      `## Описание: aria-describedby`,
      html(`<label for="pw">Пароль</label>
<input id="pw" type="password" aria-describedby="pw-rules">
<p id="pw-rules">Минимум 12 символов.</p>`),
      `Дополнительное пояснение, которое читалка прочитает после имени.`,
      `## Состояния`,
      html(`<button type="button" aria-expanded="false" aria-controls="filters">Фильтры</button>
<div id="filters" hidden>…</div>

<button type="button" aria-pressed="true">Жирный</button>`),
      `- \`aria-expanded\` — раскрыто ли управляемое меню или панель.
- \`aria-pressed\` — нажата ли кнопка-переключатель.
- \`aria-current="page"\` — текущий пункт меню.
- \`aria-invalid="true"\` — поле с ошибкой.

Состояния обновляет JavaScript вместе с самим интерфейсом.`,
      `## Живые регионы: aria-live`,
      html(`<p aria-live="polite">Товар добавлен в корзину</p>
<div role="alert">Не удалось сохранить. Проверьте подключение.</div>`),
      `Когда скрипт меняет текст внутри \`aria-live="polite"\`, читалка дочитает текущую фразу и объявит изменение. \`role="alert"\` — срочное сообщение, объявляется сразу.`,
      `## Скрыть от читалки`,
      html(`<button type="button"><span aria-hidden="true">🛒</span> Корзина</button>`),
      `\`aria-hidden="true"\` убирает элемент из дерева доступности — для декоративных иконок и эмодзи, которые дублируют текст. Никогда не ставьте его на элементы, которые получают фокус.`,
      `## Роли`,
      `\`role\` меняет смысл элемента для читалки: \`role="alert"\`, \`role="tablist"\`, \`role="img"\`. Большинство ролей уже есть у HTML-элементов: \`nav\` = \`navigation\`, \`main\` = \`main\`, \`button\` = \`button\`. Писать \`<nav role="navigation">\` бессмысленно.`,
      `## Практика`,
      `В песочнице сделайте кнопку-иконку поиска с \`aria-label\`, раздел с именем через \`aria-labelledby\` и поле с подсказкой через \`aria-describedby\`. Проверьте имена во вкладке Accessibility инструментов разработчика.`,
      mdn("../Accessibility/ARIA", "ARIA")
    ],
    quizzes: [
      single("aria-first-rule", "Первое правило", "Что гласит первое правило ARIA?",
        [["native", "Если есть подходящий нативный HTML-элемент — используйте его, а не ARIA"], ["always", "Добавляйте role ко всем элементам"], ["label", "У каждого элемента должен быть aria-label"], ["hidden", "Скрывайте всё лишнее через aria-hidden"]], "native",
        "Нативные элементы уже доступны. ARIA нужна только там, где HTML не хватает."),
      single("aria-icon-button", "Кнопка-иконка", "У кнопки только иконка «×» без текста. Как дать ей имя для читалки?",
        [["label", "aria-label=\"Закрыть\""], ["title", "Только title=\"Закрыть\""], ["alt", "alt=\"Закрыть\""], ["hidden", "aria-hidden=\"true\""]], "label",
        "aria-label задаёт доступное имя, когда видимого текста нет."),
      single("aria-live", "Сообщение о добавлении", "Скрипт показывает текст «Товар добавлен в корзину». Как сделать, чтобы читалка его объявила?",
        [["live", "Поместить текст в элемент с aria-live=\"polite\""], ["hidden", "aria-hidden=\"true\""], ["label", "aria-label на body"], ["tabindex", "tabindex=\"0\" на сообщении"]], "live",
        "Изменения внутри aria-live-региона объявляются читалкой автоматически.")
    ]
  });
}
